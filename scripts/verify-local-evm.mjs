import { ethers } from "ethers";
import fs from "fs";
import path from "path";

async function main() {
  console.log("=== LOCAL EVM BLOCKCHAIN WORKFLOW VERIFICATION ===\n");

  const rpcUrl = "http://127.0.0.1:8545";
  const provider = new ethers.JsonRpcProvider(rpcUrl);

  const network = await provider.getNetwork();
  console.log(`1. Connected to Local EVM Network:`);
  console.log(`   - RPC URL: ${rpcUrl}`);
  console.log(`   - Chain ID: ${network.chainId}`);

  // Use pre-funded accounts from Hardhat
  // Account 0 (Admin / Deployer)
  const deployer = new ethers.Wallet("0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80", provider);
  // Account 1 (Designated Issuer)
  const issuer = new ethers.Wallet("0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d", provider);
  // Account 2 (Unauthorized Learner/Attacker)
  const unauthorizedCaller = new ethers.Wallet("0x5de4111afa1a4b94908f83103eb2f95402c4e0f6729924c491c45039e917ba4e", provider);

  const balance = await provider.getBalance(deployer.address);
  console.log(`   - Deployer Address: ${deployer.address}`);
  console.log(`   - Deployer Balance: ${ethers.formatEther(balance)} ETH\n`);

  // Load compiled contract artifact
  const artifactPath = path.resolve("contracts/CertificateRegistry.json");
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  // 2. Deploy Contract
  console.log(`2. Deploying CertificateRegistry Smart Contract...`);
  const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, deployer);
  const contract = await factory.deploy();
  await contract.waitForDeployment();
  const contractAddress = await contract.getAddress();
  const deployTx = contract.deploymentTransaction();
  const deployReceipt = await deployTx.wait(1);

  console.log(`   ✅ Deployed successfully!`);
  console.log(`   - Contract Address: ${contractAddress}`);
  console.log(`   - Deployment Tx Hash: ${deployReceipt.hash}`);
  console.log(`   - Block Number: ${deployReceipt.blockNumber}`);
  console.log(`   - Gas Used: ${deployReceipt.gasUsed.toString()}\n`);

  // 3. Authorize Issuer Role
  console.log(`3. Authorizing Issuer Account: ${issuer.address}...`);
  const grantNonce = await provider.getTransactionCount(deployer.address, "latest");
  const grantTx = await contract.connect(deployer).grantIssuer(issuer.address, { nonce: grantNonce });
  const grantReceipt = await grantTx.wait(1);
  console.log(`   ✅ Issuer role granted! Tx Hash: ${grantReceipt.hash}`);
  const isAuthorized = await contract.isIssuer(issuer.address);
  console.log(`   - Contract state: isIssuer(${issuer.address}) = ${isAuthorized}\n`);

  // 4. Generate Certificate Commitment
  console.log(`4. Generating Privacy-Preserving Credential Commitment...`);
  // Realistic domain-separated SHA-256 salted commitment
  const sampleCommitment = ethers.keccak256(ethers.toUtf8Bytes(`ORELSE_LEARN_LMS_2026:LLMS-DEMO-2026-TEST:${Date.now()}`));
  console.log(`   - Generated bytes32 Commitment: ${sampleCommitment}\n`);

  // 5. Test Access Control: Unauthorized Caller must REVERT
  console.log(`5. Security Check: Unauthorized caller attempting to anchor commitment...`);
  try {
    const unauthNonce = await provider.getTransactionCount(unauthorizedCaller.address, "latest");
    await contract.connect(unauthorizedCaller).anchorCommitment(sampleCommitment, { nonce: unauthNonce });
    console.error(`   ❌ SECURITY FAILURE: Unauthorized call should have reverted!`);
    process.exit(1);
  } catch (err) {
    console.log(`   ✅ ACCESS CONTROL CONFIRMED: Unauthorized call reverted as expected (${err.message.slice(0, 50)}...)\n`);
  }

  // 6. Anchor Commitment by Authorized Issuer
  console.log(`6. Anchoring Commitment via Authorized Issuer...`);
  const issuerNonce = await provider.getTransactionCount(issuer.address, "latest");
  const anchorTx = await contract.connect(issuer).anchorCommitment(sampleCommitment, { nonce: issuerNonce });
  const anchorReceipt = await anchorTx.wait(1);
  console.log(`   ✅ Commitment Anchored On-Chain!`);
  console.log(`   - Anchoring Tx Hash: ${anchorReceipt.hash}`);
  console.log(`   - Block Number: ${anchorReceipt.blockNumber}`);
  console.log(`   - Gas Used: ${anchorReceipt.gasUsed.toString()}`);
  console.log(`   - Confirmations: 1\n`);

  // 7. Query On-Chain State
  console.log(`7. Verifying On-Chain Commitment Record...`);
  const isAnchored = await contract.isAnchored(sampleCommitment);
  const isRevoked = await contract.isRevoked(sampleCommitment);
  const commitmentRecord = await contract.getCommitment(sampleCommitment);
  console.log(`   - isAnchored: ${isAnchored}`);
  console.log(`   - isRevoked: ${isRevoked}`);
  console.log(`   - On-Chain Timestamp: ${new Date(Number(commitmentRecord[1]) * 1000).toISOString()}`);
  console.log(`   - Registered Issuer: ${commitmentRecord[2]}`);
  if (!isAnchored || isRevoked) {
    console.error(`   ❌ State mismatch!`);
    process.exit(1);
  }
  console.log(`   ✅ On-chain anchor verified.\n`);

  // 8. Test Duplicate Anchoring Prevention
  console.log(`8. Integrity Check: Attempting to anchor duplicate commitment...`);
  try {
    const dupNonce = await provider.getTransactionCount(issuer.address, "latest");
    await contract.connect(issuer).anchorCommitment(sampleCommitment, { nonce: dupNonce });
    console.error(`   ❌ FAILURE: Duplicate anchor should have reverted!`);
    process.exit(1);
  } catch (err) {
    console.log(`   ✅ IDEMPOTENCY CONFIRMED: Duplicate anchor safely prevented.\n`);
  }

  // 9. Revoke Commitment On-Chain
  console.log(`9. Revoking Certificate Commitment On-Chain...`);
  const reasonCode = ethers.keccak256(ethers.toUtf8Bytes("REASON_ADMINISTRATIVE"));
  const revokeTx = await contract.connect(issuer).revokeCommitment(sampleCommitment, reasonCode);
  const revokeReceipt = await revokeTx.wait(1);
  console.log(`   ✅ Commitment Revoked On-Chain!`);
  console.log(`   - Revocation Tx Hash: ${revokeReceipt.hash}`);
  console.log(`   - Block Number: ${revokeReceipt.blockNumber}`);
  console.log(`   - Gas Used: ${revokeReceipt.gasUsed.toString()}\n`);

  // 10. Verify Updated On-Chain State
  console.log(`10. Verifying Updated On-Chain Status...`);
  const isRevokedAfter = await contract.isRevoked(sampleCommitment);
  const onChainReasonCode = await contract.getRevocationReasonCode(sampleCommitment);
  console.log(`   - isRevoked: ${isRevokedAfter}`);
  console.log(`   - Reason Code: ${onChainReasonCode}`);
  if (!isRevokedAfter || onChainReasonCode !== reasonCode) {
    console.error(`   ❌ State mismatch after revocation!`);
    process.exit(1);
  }
  console.log(`   ✅ On-chain revocation verified.\n`);

  console.log("=================================================");
  console.log("🎉 ALL REAL LOCAL EVM WORKFLOW CHECKS PASSED!");
  console.log("=================================================");
}

main().catch((err) => {
  console.error("Execution failed:", err);
  process.exit(1);
});
